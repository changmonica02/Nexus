export function detectDefaultLanguage(): Language {
  if (typeof navigator === "undefined") return DEFAULT_LANGUAGE;
  const nav = navigator.language || "";
  return nav.toLowerCase().startsWith("zh") ? "zh-TW" : "en";
}

