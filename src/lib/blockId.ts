export function createClientBlockId(): string {
  const uuid = globalThis.crypto?.randomUUID?.();
  if (uuid) {
    return `blk_${uuid}`;
  }
  return `blk_${Date.now()}_${Math.random().toString(36).slice(2)}`;
}